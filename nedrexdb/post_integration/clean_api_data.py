import shutil
from pathlib import Path

from pymongo import MongoClient

from nedrexdb import config as _config
from nedrexdb.logger import logger

DATA_SUBDIRS_TO_CLEAN = (
    "bicon_",
    "closeness_",
    "diamond_",
    "graphs_",
    "must_",
    "neo4j_queries_",
    "network_cache_",
    "robust_",
    "trustrank_",
)

STATIC_SUBDIRS_TO_CLEAN = (
    "comorbiditome_",
    "open",
    "licensed",
)

STATIC_FILES_TO_CLEAN = (
    "GGI.gt",
    "PPI-NeDRexDB-concise.gt",
)

API_TASK_COLLECTIONS = (
    "bicon_",
    "closeness_",
    "comorbiditome_",
    "diamond_",
    "domino_",
    "graphs_",
    "kpm_",
    "must_",
    "neo4j_queries_",
    "robust_",
    "trustrank_",
    "validation_",
)

# Redis key of the pottery RedisDict in which NeDRexAPI records that its static
# ranking/validation networks have been generated (nedrexapi/common.py: _STATUS).
API_STATIC_STATUS_KEY = "static-file-status"


def _clear_directory_contents(directory: Path) -> int:
    """Remove all files and subdirectories inside `directory`, keeping `directory` itself."""
    if not directory.exists() or not directory.is_dir():
        return 0

    removed = 0
    for item in directory.iterdir():
        try:
            if item.is_dir() and not item.is_symlink():
                shutil.rmtree(item)
            else:
                item.unlink()
            removed += 1
        except Exception as e:
            logger.warning(f"Failed to remove {item}: {e}")
    return removed


def clean_api_files(data_dir: Path | None = None, static_dir: Path | None = None) -> None:
    """Clean all derived graph/network/task files generated by NeDRexAPI."""
    if data_dir is None:
        data_dir_cfg = _config.get("api.directories.data")
        data_dir = Path(data_dir_cfg) if data_dir_cfg else None
    if static_dir is None:
        static_dir_cfg = _config.get("api.directories.static")
        static_dir = Path(static_dir_cfg) if static_dir_cfg else None

    if data_dir is None or static_dir is None:
        logger.warning("API data/static directories not configured; skipping API file cleanup.")
        return

    logger.info(f"Cleaning derived API data files in {data_dir} and {static_dir}...")

    total_removed = 0
    for subdir_name in DATA_SUBDIRS_TO_CLEAN:
        subdir = data_dir / subdir_name
        count = _clear_directory_contents(subdir)
        if count:
            logger.debug(f"Removed {count} item(s) from {subdir}")
        total_removed += count

    for subdir_name in STATIC_SUBDIRS_TO_CLEAN:
        subdir = static_dir / subdir_name
        count = _clear_directory_contents(subdir)
        if count:
            logger.debug(f"Removed {count} item(s) from {subdir}")
        total_removed += count

    for fname in STATIC_FILES_TO_CLEAN:
        fpath = static_dir / fname
        if fpath.exists():
            try:
                fpath.unlink()
                total_removed += 1
                logger.debug(f"Removed static validation file {fpath}")
            except Exception as e:
                logger.warning(f"Failed to remove static validation file {fpath}: {e}")

    logger.info(f"Finished cleaning derived API files (removed {total_removed} item(s)).")


def reset_api_static_status() -> None:
    """Make NeDRexAPI regenerate its static ranking/validation networks.

    The API skips regeneration while its Redis status dict says the files exist,
    and it only clears that dict when the API runner starts. Since the files were
    just deleted, the dict has to be deleted too, or ranking and validation jobs
    fail until the API is restarted.
    """
    consequence = (
        "NeDRexAPI will not regenerate its ranking/validation networks until it is restarted"
    )
    host = _config.get("api.redis_host")
    port = _config.get("api.redis_port_internal") or 6379
    db = _config.get("api.redis_nedrex_db")

    if not host or db is None:
        logger.warning(f"API Redis not configured; {consequence}.")
        return

    try:
        from redis import Redis

        client = Redis(host=host, port=port, db=db, socket_connect_timeout=5, socket_timeout=5)
        deleted = client.delete(API_STATIC_STATUS_KEY)
        client.close()
        logger.info(
            f"Reset API static file status on Redis ({host}:{port}/{db}, removed {deleted} key(s))."
        )
    except Exception as e:
        logger.warning(f"Could not reset API static file status on Redis ({host}:{port}/{db}): {e}. {consequence}.")


def clean_api_db() -> None:
    """Drop derived task/graph collections in the live `nedrexapi` MongoDB database.

    Safety net only: a promotion starts the live MongoDB on the freshly built
    volume, which has no `nedrexapi` database, so this normally finds nothing.
    """
    host = _config.get("db.live.mongo_name")
    port = _config.get("api.mongo_port_internal") or _config.get("db.live.mongo_port_internal") or 27017
    api_db_name = _config.get("api.mongo_db") or "nedrexapi"

    if not host:
        logger.warning("Live MongoDB host not configured; skipping API DB cleanup.")
        return

    try:
        client = MongoClient(host=host, port=port, serverSelectionTimeoutMS=5000)
        db = client[api_db_name]
        existing_collections = set(db.list_collection_names())
        dropped = 0
        for coll_name in API_TASK_COLLECTIONS:
            if coll_name in existing_collections:
                db[coll_name].drop()
                dropped += 1
        client.close()
        logger.info(f"Cleaned {dropped} task collection(s) from live MongoDB ({api_db_name!r} on {host}).")
    except Exception as e:
        logger.warning(f"Could not clean API task collections on live MongoDB ({host}:{port}): {e}")


def clean_after_update(data_dir: Path | None = None, static_dir: Path | None = None) -> None:
    """Full cleanup of derived API files and DB task records after a successful KG update."""
    clean_api_files(data_dir=data_dir, static_dir=static_dir)
    reset_api_static_status()
    clean_api_db()
